// Generates android/app/src/main/java/au/sunrise/alarm/ThemeData.kt from the page's THEMES (index.html),
// so the native night, alarm and morning screens use exactly the same colours.
// Run: node tools/gen-theme-data.js > android/app/src/main/java/au/sunrise/alarm/ThemeData.kt
// tests/themes.test.js checks the committed file is up to date.
const fs = require("fs"), path = require("path");

function generate() {
  const html = fs.readFileSync(path.join(__dirname, "..", "index.html"), "utf8");
  const start = html.indexOf("let THEMES = {");
  const end = html.indexOf("\n  };", start) + 4;
  const THEMES = new Function(html.slice(start, end).replace("let THEMES =", "return ") )();
  const hex = c => "0x" + c.slice(1).toLowerCase();
  const stops = s => "listOf(" + s.map(([p, c]) => `${p}f to ${hex(c)}`).join(", ") + ")";
  const vars = v => "mapOf(" + Object.entries(v).map(([k, c]) => `"${k}" to ${hex(c)}`).join(", ") + ")";
  const out = [];
  out.push("package au.sunrise.alarm");
  out.push("");
  out.push("// GENERATED by tools/gen-theme-data.js from THEMES in index.html. Don't edit by hand.");
  out.push("");
  out.push("/** Every colour a theme uses on the night, alarm and morning screens (0xRRGGBB). */");
  out.push("object ThemeData {");
  out.push("    val ALL: Map<String, FullTheme> = mapOf(");
  for (const [key, t] of Object.entries(THEMES)) {
    out.push(`        "${key}" to FullTheme(`);
    out.push(`            name = "${t.name}",`);
    out.push(`            vars = ${vars(t.vars)},`);
    out.push(`            sky = ${stops(t.sky)},`);
    out.push(`            glow = ${stops(t.glow)},`);
    out.push(`            night = listOf(${t.night.map(hex).join(", ")}),`);
    out.push(`            clockMid = ${hex(t.clockMid)}, clockHi = ${hex(t.clockHi)}, clockEnd = ${hex(t.clockEnd)},`);
    out.push("        ),");
  }
  out.push("    )");
  out.push("}");
  return out.join("\n") + "\n";
}

module.exports = { generate };
if (require.main === module) process.stdout.write(generate());
